"""Generate every LaTeX table for the paper from paper/analysis/statistics.json.

Output: paper/tables/*.tex. No number is hand-typed anywhere: every table is
rendered from the statistics JSON produced by scripts/statistical_analysis.py,
which in turn is derived from results/registry_paper.jsonl + results/runs/*.json.

Run:  python3 scripts/generate_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

from paper_common import SHORT_MODEL  # noqa: E402

STATS = REPO / "paper" / "analysis" / "statistics.json"
OUT = REPO / "paper" / "tables"

MODEL_ORDER = ["Phi-3.5-mini", "Qwen2.5-3B", "SmolLM2-1.7B"]
MODEL_HF = {
    "Phi-3.5-mini": "microsoft/Phi-3.5-mini-instruct",
    "Qwen2.5-3B": "Qwen/Qwen2.5-3B-Instruct",
    "SmolLM2-1.7B": "HuggingFaceTB/SmolLM2-1.7B-Instruct",
    "Qwen2.5-7B": "Qwen/Qwen2.5-7B-Instruct",
}
MODEL_PARAMS = {"Phi-3.5-mini": 3.8, "Qwen2.5-3B": 3.1, "SmolLM2-1.7B": 1.7, "Qwen2.5-7B": 7.6}
TASKS = ["arc_easy", "gsm8k", "hellaswag", "mgsm"]
BENCH = [
    ("ARC-Easy", "allenai/ai2_arc", "test", "CC-BY-SA-4.0", "210d026f"),
    ("GSM8K", "openai/gsm8k", "test", "MIT", "740312ad"),
    ("HellaSwag", "Rowan/hellaswag", "validation", "MIT", "218ec52e"),
    ("MGSM (EN/DE/FR)", "juletxara/mgsm", "test", "MIT", "b2f13d42"),
]
FACTOR_DISPLAY = {
    "prompt_id": "Prompt", "backend": "Backend", "quantization": "Quantization",
    "seed": "Greedy seed", "sampled": "Sampling",
}
LEVEL_DISPLAY = {
    "vllm": "vLLM", "int8": "INT8", "int4": "INT4", "5shot": "5-shot",
    "concise": "Concise", "default": "Default",
    "t0.7_seed0": "T=0.7, s0", "t0.7_seed1": "T=0.7, s1", "t0.7_seed2": "T=0.7, s2",
}


def esc(s: str) -> str:
    return str(s).replace("_", r"\_")


def fmt_acc(x: float) -> str:
    return f"{100.0 * x:.1f}"


def fmt_ci(ci: list[float]) -> str:
    return f"[{100.0 * ci[0]:.1f}, {100.0 * ci[1]:.1f}]"


def cfg_label(raw: str) -> str:
    if raw == "control":
        return "Control"
    for k in ("prompt_id=", "backend=", "quantization=", "seed=", "sampled="):
        raw = raw.replace(k, "")
    return raw.replace("t0.7_", "T=0.7 s")


def table(body: str, header: str, spec: str, caption: str, label: str) -> str:
    return (
        "% Auto-generated by scripts/generate_tables.py -- do not edit.\n"
        "\\begin{table}[t]\n\\centering\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n\\small\n\\setlength{{\\tabcolsep}}{{5pt}}\n"
        f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header}\\midrule\n"
        f"{body}\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n"
    )

def main() -> int:
    d = json.loads(STATS.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    written = []

    def w(name: str, text: str) -> None:
        (OUT / name).write_text(text, encoding="utf-8")
        written.append(name)

    cells_per_model: dict[str, int] = {}
    per_model_factors: dict[str, dict[str, int]] = {}
    for v in d["registry_verification"]:
        short = SHORT_MODEL.get(v["settings"]["model_id"], v["settings"]["model_id"])
        cells_per_model[short] = cells_per_model.get(short, 0) + 1
        per_model_factors.setdefault(short, {})

    # ------------------------------------------------------------------ models
    rows = []
    for mk, hf in MODEL_HF.items():
        n = cells_per_model.get(mk, 0)
        note = "" if n > 1 else " (single cell)"
        rows.append(f"{esc(mk)} & {esc(hf)} & {MODEL_PARAMS[mk]:.1f} & {n}{note} \\\\")
    w("models.tex", table(
        "\n".join(rows) + "\n",
        "Model & Hugging Face ID & Params (B) & Cells \\\\\n",
        "llrc",
        "Evaluated models. ``Cells'' counts completed configurations with"
        " \\texttt{status=ok} in the committed registry. Qwen2.5-7B was measured"
        " only under INT4 weight-only quantization: its fp16/int8/vLLM cells"
        " exceed the 16\\,GB Tesla~T4 budget, so it is excluded from ranking"
        " analyses and appears in no ranking table.",
        "tab:models",
    ))

    # --------------------------------------------------------------- benchmarks
    rows = [
        f"{esc(t)} & {esc(hf)} & {split} & 200 & {lic} & \\texttt{{{sha}}} \\\\"
        for t, hf, split, lic, sha in BENCH
    ]
    w("benchmarks.tex", table(
        "\n".join(rows) + "\n",
        "Task & Hugging Face dataset & Split & $n$ & License & Hub revision \\\\\n",
        "llllll",
        "Frozen benchmark slices (generative exact-match; shuffled with seed 0,"
        " first 200 items per task; MGSM pooled over English, German, French)."
        " Hub revisions are pinned in the committed"
        " \\texttt{data/official/SOURCES.md}; slice files carry content SHA-256"
        " hashes in the artifact catalog. This generative letter/number"
        " extraction protocol is not the lm-eval loglikelihood protocol, so"
        " scores are not comparable to leaderboard numbers.",
        "tab:benchmarks",
    ))

    # ------------------------------------------------------------ main results
    ctl = d["control"]
    rows = []
    for mk in MODEL_ORDER:
        c = ctl[mk]
        per_task = " & ".join(
            f"{c['tasks'][t]['correct']}/{c['tasks'][t]['n']}" for t in TASKS
        )
        rows.append(
            f"{esc(mk)} & {per_task} & {fmt_acc(c['accuracy'])} & {fmt_ci(c['ci95'])} \\\\"
        )
    w("main_results.tex", table(
        "\n".join(rows) + "\n",
        "Model & ARC & GSM8K & HSwag & MGSM & Overall (\\%) & 95\\% CI \\\\\n",
        "lcccccc",
        "Control configuration: Hugging Face \\texttt{generate}, tokenizer chat"
        " template, greedy decoding (temperature 0, top-$p$ 1, seed 0), no"
        " quantization, default zero-shot prompt, frozen 800-item slice, NVIDIA"
        " Tesla T4. Correct counts per task out of 200; overall accuracy with"
        " Wilson 95\\% CIs. The Phi-3.5-mini and Qwen2.5-3B intervals overlap:"
        " the control configuration alone does not statistically separate the"
        " top two models.",
        "tab:control",
    ))

    # ------------------------------------------------------- sensitivity table
    order = ["prompt_id", "quantization", "backend", "sampled", "seed"]
    grouped: dict[str, list[dict]] = {mk: [] for mk in MODEL_ORDER}
    for c in d["contrasts"]:
        grouped[c["model"]].append(c)
    rows = []
    for mk in MODEL_ORDER:
        first = True
        for fac in order:
            cells_ = sorted(
                (c for c in grouped[mk] if c["factor"] == fac),
                key=lambda c: c["level"],
            )
            for c in cells_:
                mdl = esc(mk) if first else ""
                first = False
                holm = c["p_holm"]
                holm_s = "$<$0.001" if holm < 0.001 else f"{holm:.3f}"
                sig = r"$^\ast$" if holm < 0.05 else ""
                rows.append(
                    f"{mdl} & {esc(FACTOR_DISPLAY.get(c['factor'], c['factor']))} & "
                    f"{esc(LEVEL_DISPLAY.get(c['level'], c['level']))} & "
                    f"{fmt_acc(c['acc_variant'])} & {c['delta_pp']:+.2f} & "
                    f"{c['cohens_h']:+.3f} & {holm_s}{sig} \\\\"
                )
        rows.append(r"\addlinespace")
    while rows and rows[-1] == r"\addlinespace":
        rows.pop()
    w("sensitivity.tex", table(
        "\n".join(rows) + "\n",
        "Model & Factor & Level & Acc.\\ (\\%) & $\\Delta$ (pp) & $h$ & $p$ \\\\\n",
        "lllrrrl",
        "One-factor-at-a-time contrasts against each model's control"
        " configuration (800 paired items). $\\Delta$ is the accuracy change in"
        " percentage points; $h$ is Cohen's $h$; $p$ is the Holm--Bonferroni"
        " adjusted $p$-value of the continuity-corrected McNemar test over the"
        " full family of 27 contrasts ($^\\ast$ = $p<0.05$ after adjustment)."
        " Sampling rows use temperature 0.7, top-$p$ 0.95; greedy-seed rows"
        " change only the RNG seed under temperature 0 and are item-for-item"
        " identical to the control (deterministic decoding).",
        "tab:sensitivity",
    ))

    # --------------------------------------------------- ranking stability table
    rk = d["ranking"]
    accs = rk["matrix"]
    tau_rows = rk["tau_vs_control"]
    midx = {m: rk["models"].index(m) for m in MODEL_ORDER}
    rows = []
    for ci in range(len(rk["config_labels"])):
        tr = tau_rows[ci]
        cells_ = [fmt_acc(accs[midx[m]][ci]) for m in MODEL_ORDER]
        if tr["measured"]:
            # tr["ranks"] is in rk["models"] order; reorder to MODEL_ORDER
            # (Phi / Qwen / Smol) so the column header stays truthful.
            rank_str = " / ".join(
                str(int(tr["ranks"][rk["models"].index(m)])) for m in MODEL_ORDER
            )
            tau_s = f"{tr['tau_b']:.2f}"
            rev_s = str(tr["reversals"])
        else:
            rank_str, tau_s, rev_s = "--", "--", "--"
        rows.append(
            f"{esc(cfg_label(rk['config_labels'][ci]))} & {' & '.join(cells_)} &"
            f" {rank_str} & {tau_s} & {rev_s} \\\\"
        )
    meanranks = " & ".join(
        f"{rk['rank_distributions'][midx[m]]['mean_rank']:.2f}" for m in MODEL_ORDER
    )
    p1 = " / ".join(
        f"{100.0 * rk['rank_distributions'][midx[m]]['p_rank_1']:.1f}\\%" for m in MODEL_ORDER
    )
    body = "\n".join(rows) + (
        f"\n\\midrule\n"
        f"Mean rank (1 = best) & {meanranks} &"
        f" \\multicolumn{{3}}{{c}}{{$P(\\#1)$: {p1}}} \\\\\n"
    )
    w("ranking_stability.tex", table(
        body,
        "Configuration & Phi & Qwen & Smol & Ranks (P/Q/S) & $\\tau_b$ & Rev. \\\\\n",
        "lccccll",
        "Model scores and ranking across the eight configurations measured for"
        " all three fully-evaluated models. Accuracy in \\%; ranks are"
        " competition ranks by overall accuracy (1 = best, listed Phi / Qwen /"
        " SmolLM2); $\\tau_b$ is Kendall's tau-b against the control-config"
        " ranking, with the number of pairwise reversals. The five-shot prompt"
        " produces the only ranking change ($\\tau_b=0.33$, one reversal):"
        " Qwen2.5-3B and Phi-3.5-mini swap first and second place.",
        "tab:ranking",
    ))

    # ----------------------------------------------------- head-to-head table
    h2h = rk["phi_vs_qwen_head_to_head"]
    rows = []
    for h in h2h:
        rows.append(
            f"{esc(cfg_label(h['config']))} & {fmt_acc(h['phi_acc'])} &"
            f" {fmt_acc(h['qwen_acc'])} & {h['phi_minus_qwen_pp']:+.2f} &"
            f" {'yes' if h['ci_disjoint'] else 'no'} & {h['winner']} \\\\"
        )
    w("head_to_head.tex", table(
        "\n".join(rows) + "\n",
        "Configuration & Phi (\\%) & Qwen (\\%) & $\\Phi{-}Q$ (pp) & CIs disjoint & Leader \\\\\n",
        "lrrrcc",
        "Phi-3.5-mini vs.\\ Qwen2.5-3B head-to-head across the eight shared"
        " configurations. ``Disjoint'' means the two Wilson 95\\% intervals do"
        " not overlap. The control-config difference (+2.62\\,pp) is not"
        " statistically separated; the five-shot configuration flips the order"
        " with disjoint intervals and the largest gap in the matrix.",
        "tab:h2h",
    ))

    # ---------------------------------------------------------- sampling table
    samp = d["sampling"]
    rows = []
    for mk in ["Qwen2.5-3B", "SmolLM2-1.7B"]:
        s = samp[mk]
        seed_cells = [
            fmt_acc(s["sampled_seeds"][lvl]["accuracy"])
            for lvl in ("t0.7_seed0", "t0.7_seed1", "t0.7_seed2")
        ]
        gs = s["greedy_seeds"]
        noop = "yes (0/800)" if gs["1"]["identical_to_control"] else "no"
        rows.append(
            f"{esc(mk)} & {fmt_acc(s['control_accuracy'])} &"
            f" {' & '.join(seed_cells)} & {s['sampled_range_pp']:.2f} & {noop} \\\\"
        )
    w("sampling.tex", table(
        "\n".join(rows) + "\n",
        "Model & Greedy (T=0) & T=0.7, s0 & T=0.7, s1 & T=0.7, s2 & Range (pp) & Greedy-seed no-op \\\\\n",
        "lcccccc",
        "Decoding stochasticity versus determinism. Sampled columns use"
        " temperature 0.7, top-$p$ 0.95 with three different seeds; the range"
        " across seeds is in percentage points. Greedy-seed rows change only the"
        " RNG seed under temperature 0: the committed runs are item-for-item"
        " identical to the control (0 discordant pairs out of 800), so greedy"
        " seed variation contributes exactly zero measured variance in this"
        " harness.",
        "tab:sampling",
    ))

    # ------------------------------------- appendix: all contrasts (raw p, Holm, BH)
    rows = []
    for c in d["contrasts"]:
        p = c["mcnemar"]["p_value"]
        p_s = "$<$0.001" if p < 0.001 else f"{p:.4f}"
        rows.append(
            f"{esc(c['model'])} & {esc(FACTOR_DISPLAY.get(c['factor'], c['factor']))} &"
            f" {esc(LEVEL_DISPLAY.get(c['level'], c['level']))} &"
            f" {c['mcnemar']['a_correct_b_wrong']} & {c['mcnemar']['a_wrong_b_correct']} &"
            f" {c['mcnemar']['disagreement_rate']:.3f} & {p_s} & {c['p_holm']:.4f} &"
            f" {c['p_bh']:.4f} \\\\"
        )
    w("appendix_contrasts.tex", table(
        "\n".join(rows) + "\n",
        "Model & Factor & Level & A-only & B-only & Disagr. & $p$ (McN) & $p$ (Holm) & $p$ (BH) \\\\\n",
        "lllrrrrrr",
        "All 27 paired OFAT contrasts against each model's control"
        " configuration (800 items per contrast). ``A-only'' counts items"
        " correct under the control and wrong under the variant; ``B-only''"
        " counts the reverse; ``Disagr.'' is the total disagreement rate. Raw"
        " (continuity-corrected McNemar), Holm-adjusted, and"
        " Benjamini--Hochberg-adjusted $p$-values over the full 27-test family.",
        "tab:appendix-contrasts",
    ))

    # ---------------------------------------- appendix: coverage per model/factor
    # NOTE: `factor` is a row-level field of the registry and is not stored in
    # the run artifact's settings block, so it is recovered from the run_id,
    # which has the form "<model>_<factor>_<level>_<config_hash>".
    FACTOR_NAMES = ("control", "prompt_id", "quantization", "backend", "seed", "sampled")
    COL_OF_FACTOR = {
        "control": "control",
        "prompt_id": "prompt_id",
        "quantization": "quantization",
        "backend": "backend",
        "seed": "seed",
        "sampled": "sampling",
    }

    def factor_of(run_id: str) -> str:
        for f in FACTOR_NAMES:
            if f"_{f}_" in run_id:
                return f
        return "unknown"

    fac_counts: dict[str, dict[str, int]] = {mk: {} for mk in MODEL_HF}
    for v in d["registry_verification"]:
        s = v["settings"]
        short = SHORT_MODEL.get(s["model_id"], s["model_id"])
        if s["experiment_id"] != "stability":
            continue
        key = COL_OF_FACTOR.get(factor_of(v["run_id"]), "unknown")
        fac_counts[short][key] = fac_counts[short].get(key, 0) + 1
    cols = ["control", "prompt_id", "quantization", "backend", "seed", "sampling"]
    rows = []
    for mk in MODEL_HF:
        fc = fac_counts[mk]
        vals = " & ".join(str(fc.get(c, 0)) for c in cols)
        rows.append(f"{esc(mk)} & {vals} & {cells_per_model.get(mk, 0)} \\\\")
    prov = d["provenance"]
    n_commits = len(prov["git_commits"])
    body = "\n".join(rows) + (
        f"\n\\midrule\n\\multicolumn{{8}}{{p{{0.94\\linewidth}}}}{{Total: {prov['n_registry_ok']} of"
        f" {prov['n_planned_t4_cells']} planned T4 cells; {prov['n_missing_cells']}"
        f" missing (Phi sampled, seeds 0--2). Runs span {n_commits} git commits,"
        f" {prov['utc_first'][:10]} to {prov['utc_last'][:10]}.}} \\\\\n"
    )
    w("appendix_coverage.tex", table(
        body,
        "Model & Control & Prompt & Quant. & Backend & Seed & Sampling & Total \\\\\n",
        "lccccccr",
        "Committed paper-matrix coverage per model and factor. Every cell is one"
        " completed run with a frozen 800-item slice, a full manifest (settings,"
        " package versions, hardware), and a SHA-256-derived configuration hash"
        " registered in \\texttt{results/registry\\_paper.jsonl}.",
        "tab:coverage",
    ))

    # ----------------------------------------------- appendix: latency (measured)
    rows = []
    for key in sorted(d["latency"]):
        v = d["latency"][key]
        model, _, cfg = key.partition("|")
        if v["status"] == "MEASURED":
            rows.append(
                f"{esc(model)} & {esc(cfg_label(cfg))} & {v['ttft_ms_mean']:.1f} &"
                f" {v['e2e_ms_mean']:.1f} & {v['tokens_per_sec_mean']:.2f} \\\\"
            )
        else:
            rows.append(
                f"{esc(model)} & {esc(cfg_label(cfg))} & \\multicolumn{{3}}{{c}}{{UNAVAILABLE (backend timing placeholder)}} \\\\"
            )
    w("appendix_latency.tex", table(
        "\n".join(rows) + "\n",
        "Model & Config & TTFT (ms) & E2E (ms) & Tokens/s \\\\\n",
        "llccc",
        "Runtime measured per run by the harness (mean over 800 items,"
        " batch size 1, Tesla T4). Committed vLLM cells store 0.0 placeholders"
        " for timing; following the repository cost model these are treated as"
        " UNAVAILABLE rather than read as zero milliseconds, so no HF-vs-vLLM"
        " latency comparison is claimed.",
        "tab:latency",
    ))

    # ------------------------------------------------------- appendix: ERS
    ers = d["ers"]["matrix_8_configs"]
    seed_ers = d["ers"]["with_seed_component"]
    comp = ers["components"]
    seed_comp = seed_ers["components"]["seed_stability"]
    seed_cell = f"{seed_comp:.4f}" if isinstance(seed_comp, float) else "---"
    body = (
        f"ci\\_separation & {comp['ci_separation']:.4f} & 0.40 \\\\\n"
        f"bootstrap\\_tau & {comp['bootstrap_tau']:.4f} & 0.30 \\\\\n"
        f"config\\_stability & {comp['config_stability']:.4f} & 0.20 \\\\\n"
        f"seed\\_stability (seed scores supplied) & {seed_cell} & 0.10 \\\\\n\\midrule\n"
        f"ERS (3 components) & \\multicolumn{{2}}{{c}}{{{ers['ers']:.4f}}} \\\\\n"
        f"ERS (4 components) & \\multicolumn{{2}}{{c}}{{{seed_ers['ers']:.4f}}} \\\\\n"
    )
    w("appendix_ers.tex", table(
        body,
        "Component & Value & Default weight \\\\\n",
        "lcc",
        f"Provisional Evaluation Reliability Score over the eight-configuration"
        f" matrix (seeded bootstrap, 2000 replicates; mean tau"
        f" {ers['bootstrap']['mean_tau']:.4f}, probability of at least one"
        f" pairwise reversal under config resampling"
        f" {ers['bootstrap']['p_any_reversal']:.4f}). ERS is an exploratory"
        f" composite proposed by this framework, not a validated metric: its"
        f" components are reported individually throughout the paper, and its"
        f" weights are provisional. Higher values are intended to indicate more"
        f" reliable model separation.",
        "tab:ers",
    ))

    print("wrote:", ", ".join(written))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())




