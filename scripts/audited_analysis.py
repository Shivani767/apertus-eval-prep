"""Audited paired analysis and compact paper tables from raw stored predictions.

No inference. Stratified paired item bootstrap preserves task sample sizes.
Intervals are conditional approximations: translated/related items are not
independent, so these are not cluster-robust population intervals.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
from paper_common import load_paper_data, MODELS_IN_MATRIX, SHORT_MODEL, SHARED_CONFIGS, REPO_ROOT
from apertus_eval_prep.stats import holm_bonferroni, kendall_tau_b, wilson_interval

OUT = REPO_ROOT / 'paper/analysis'
TABLES = REPO_ROOT / 'paper/tables'
N_BOOT = 4000
SEED = 0

def paired(a, b, n_boot=N_BOOT, seed=SEED):
    aa = {i['id']: i for i in a}; bb = {i['id']: i for i in b}
    if len(aa) != len(a) or len(bb) != len(b) or set(aa) != set(bb) or not aa:
        raise ValueError('paired analysis requires identical unique nonempty IDs')
    rng = np.random.default_rng(seed)
    replicates = np.zeros(n_boot)
    counts = []
    for task in sorted({i['task'] for i in a}):
        ids = sorted(i for i in aa if aa[i]['task'] == task)
        diffs = []
        for i in ids:
            if aa[i]['task'] != bb[i]['task'] or aa[i]['gold'] != bb[i]['gold']:
                raise ValueError('paired metadata mismatch')
            if type(aa[i]['correct']) is not bool or type(bb[i]['correct']) is not bool:
                raise ValueError('nonboolean correctness')
            diffs.append(int(bb[i]['correct']) - int(aa[i]['correct']))
        freq = np.array([diffs.count(v) for v in (-1, 0, 1)])
        draws = rng.multinomial(len(ids), freq / len(ids), size=n_boot)
        replicates += draws[:, 2] - draws[:, 0]
        counts.extend(diffs)
    # Exact conditional binomial McNemar test: no asymptotic/small-count issue.
    import math
    losses, wins = counts.count(-1), counts.count(1)
    discordant = losses + wins
    p = min(1.0, 2 * sum(math.comb(discordant, k) for k in range(min(losses, wins) + 1)) / 2 ** discordant) if discordant else 1.0
    lo, hi = np.quantile(replicates / len(a) * 100, [.025, .975], method='linear')
    return {'n': len(a), 'losses': losses, 'wins': wins, 'delta_pp': 100 * sum(counts) / len(a), 'ci95_pp': [float(lo), float(hi)], 'p_exact': p, 'n_boot': n_boot, 'seed': seed}

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def tex_table(name, caption, label, header, spec, rows):
    text = '% Generated by scripts/audited_analysis.py\n'
    text += '\\begin{table}[tbp]\n\\centering\\small\n\\caption{' + caption + '}\\label{' + label + '}\n'
    text += '\\begin{tabular}{' + spec + '}\\toprule\n' + header + r' \\' + '\n\\midrule\n'
    text += '\n'.join(' & '.join(map(str, r)) + r' \\' for r in rows)
    text += '\n\\bottomrule\\end{tabular}\n\\end{table}\n'
    (TABLES / name).write_text(text)

def pformat(p):
    return f'{p:.3g}' if p >= .001 else '$<0.001$'

def main():
    data = load_paper_data()
    if data['problems']:
        raise ValueError(data['problems'])
    cells, blobs = data['cells'], data['blobs']
    def items(m, f, l):
        return blobs[cells[(m, f, l)]['run_id']]['items']
    contrasts = []
    for (m, f, l), c in sorted(cells.items()):
        if m not in MODELS_IN_MATRIX or f == 'control':
            continue
        rec = paired(items(m, 'control', 'control'), items(m, f, l))
        rec.update(model=SHORT_MODEL[m], factor=f, level=l, run_id=c['run_id'], control_id=cells[(m, 'control', 'control')]['run_id'])
        contrasts.append(rec)
    for r, p in zip(contrasts, holm_bonferroni([r['p_exact'] for r in contrasts])):
        r['p_holm'] = p
    h2h = []
    phi, qwen = MODELS_IN_MATRIX[2], MODELS_IN_MATRIX[1]
    for f, l in SHARED_CONFIGS:
        r = paired(items(phi, f, l), items(qwen, f, l))
        r.update(config=f'{f}={l}', phi_id=cells[(phi, f, l)]['run_id'], qwen_id=cells[(qwen, f, l)]['run_id'])
        h2h.append(r)
    for r, p in zip(h2h, holm_bonferroni([r['p_exact'] for r in h2h])):
        r['p_holm'] = p
    sources = [REPO_ROOT / r['path'] for r in data['rows']]
    sources += [REPO_ROOT / 'results/registry_paper.jsonl', REPO_ROOT / 'data/official/eval_set.jsonl', REPO_ROOT / 'data/official/fewshot.jsonl', REPO_ROOT / 'configs/experiments/stability.yaml']
    sources += list((REPO_ROOT / 'configs/prompts').glob('*.yaml'))
    sources += list((REPO_ROOT / 'src/apertus_eval_prep').rglob('*.py'))
    sources += [REPO_ROOT / 'scripts' / name for name in ('audited_analysis.py', 'paper_common.py', 'statistical_analysis.py', 'generate_figures.py', 'validate_paper.py', 'reproduce_paper.py')]
    sources += [REPO_ROOT / 'pyproject.toml', REPO_ROOT / 'Makefile']
    output = {'method': 'exact McNemar + task-stratified paired bootstrap; conditional item-independence approximation', 'contrasts': contrasts, 'head_to_head': h2h, 'sources': {str(p.relative_to(REPO_ROOT)): sha(p) for p in sorted(sources)}}
    OUT.mkdir(exist_ok=True); TABLES.mkdir(exist_ok=True)
    (OUT / 'audited_statistics.json').write_text(json.dumps(output, indent=2, allow_nan=False) + '\n')
    render(data, output)
    print('Audited analysis: raw paired contrasts, exact tests, Holm families, bootstrap intervals and source hashes generated.')

def render(data, output):
    render_master(data, output)
    cells = data['cells']
    rows = []
    for m in MODELS_IN_MATRIX:
        c = cells[(m, 'control', 'control')]
        n, k = c['overall']['n'], c['overall']['correct']
        lo, hi = wilson_interval(k, n)
        rows.append([SHORT_MODEL[m], f'{k}/{n}', f'{100*k/n:.3f}', f'[{100*lo:.2f}, {100*hi:.2f}]'])
    tex_table('audited_control.tex', 'Control extracted-answer accuracy. Wilson intervals are conditional binomial approximations, not equivalence tests.', 'tab:control', 'Model & Correct/items & Accuracy (\\%) & 95\\% interval', 'llrr', rows)
    rows = []
    for r in output['contrasts']:
        if r['factor'] not in ('prompt_id', 'backend', 'quantization'):
            continue
        rows.append([r['model'], r['level'], f"{r['delta_pp']:+.3f}", f"[{r['ci95_pp'][0]:.2f}, {r['ci95_pp'][1]:.2f}]", pformat(r['p_holm'])])
    tex_table('audited_sensitivity.tex', 'Variant minus control (percentage points). Task-stratified paired bootstrap intervals; exact McNemar p-values adjusted with Holm over all non-control same-model contrasts, including seeds and sampling. Intervals are pointwise, not simultaneous.', 'tab:sensitivity', 'Model & Variant & Difference (pp) & 95\\% interval & Holm $p$', 'llrrr', rows)
    rows = []
    for r in output['head_to_head']:
        label = r['config'].replace('control=control', 'control').replace('prompt_id=', '').replace('quantization=', '').replace('backend=', '').replace('seed=', 'seed ')
        rows.append([label, f"{r['delta_pp']:+.3f}", f"[{r['ci95_pp'][0]:.2f}, {r['ci95_pp'][1]:.2f}]", pformat(r['p_holm'])])
    tex_table('audited_head_to_head.tex', 'Qwen minus Phi: paired model comparison. Holm correction covers the separate family of shared-configuration comparisons. Positive values favor Qwen. Conditional, post-hoc analysis; no claim of equivalence from non-significance.', 'tab:h2h', 'Configuration & Difference (pp) & 95\\% interval & Holm $p$', 'lrrr', rows)
    stats = json.loads((OUT / 'statistics.json').read_text())
    rows = []
    for r in stats['ranking']['tau_vs_control']:
        label = r['config'].replace('prompt_id=', '').replace('quantization=', '').replace('backend=', '').replace('seed=', 'seed ')
        rows.append([label, '/'.join(str(int(x)) for x in r['ranks']), f"{r['tau_b']:.3f}", r['reversals']])
    tex_table('audited_ranking.tex', 'Ranks ordered Smol/Qwen/Phi, Kendall tau-b against control, and pairwise reversals. Ties would receive shared ranks; none occur in these columns.', 'tab:ranking', 'Configuration & Ranks & $\\tau_b$ & Reversals', 'lrrr', rows)
    from collections import Counter
    failure_rows, task_rows, details = [], [], []
    for m in sorted({r['model_id'] for r in data['rows']}):
        records = [it for r in data['rows'] if r['model_id'] == m for it in data['blobs'][r['run_id']]['items']]
        categories = Counter('correct' if it['correct'] else 'empty' if not it['generation'].strip() else 'unparseable' if it['predicted'] is None else 'incorrect' for it in records)
        failure_rows.append([SHORT_MODEL[m], len(records), categories['correct'], categories['incorrect'], categories['unparseable'], categories['empty']])
    tex_table('audited_failures.tex', 'Post-hoc output categories across all successful paper runs, including sampled and single-cell runs. Denominator counts repeated outputs, not independent questions. Runtime failures/timeouts outside archived successful runs are unknown, not zero.', 'tab:failures', 'Model & Outputs & Correct & Incorrect & Unparseable & Empty', 'lrrrrr', failure_rows)
    for r in data['rows']:
        b = data['blobs'][r['run_id']]
        details.append({'run_id': r['run_id'], 'manifest': b['manifest'], 'tasks': b['tasks']})
        if r['factor'] == 'control':
            for t, s in sorted(b['tasks'].items()):
                if t != 'overall':
                    task_rows.append([SHORT_MODEL[r['model_id']], t.replace('_', r'\_'), s['correct'], s['n'], f"{100*s['accuracy']:.2f}"])
    tex_table('audited_tasks.tex', 'Control task-level extracted-answer accuracy; the full task breakdown for every run is exported in run details.', 'tab:tasks', 'Model & Task & Correct & Items & Accuracy (\\%)', 'llrrr', task_rows)
    (OUT / 'run_details.json').write_text(json.dumps(details, indent=2, allow_nan=False) + '\n')
    q, phi = MODELS_IN_MATRIX[1], MODELS_IN_MATRIX[2]
    def score(m, f, l):
        return cells[(m, f, l)]['overall']['accuracy']
    values = {'RunCount': str(len(data['rows'])), 'ItemCount': str(len(next(iter(data['blobs'].values()))['items'])), 'ContrastCount': str(len(output['contrasts'])), 'PromptRange': f"{100*(score(q,'prompt_id','5shot')-score(q,'prompt_id','concise')):.3f}", 'ControlGap': f"{100*(score(phi,'control','control')-score(q,'control','control')):.3f}", 'FiveShotGap': f"{output['head_to_head'][2]['delta_pp']:.3f}", 'ControlPairedP': f"{output['head_to_head'][0]['p_holm']:.3f}"}
    (TABLES / 'numbers.tex').write_text('% Generated numerical claims\n' + '\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in values.items()) + '\n')

def render_master(data, output):
    """One row per archived cell; exact paired p-values match the main tables."""
    contrasts = {r['run_id']: r for r in output['contrasts']}
    rows = []
    for row in data['rows']:
        n, k = row['overall']['n'], row['overall']['correct']
        lo, hi = wilson_interval(k, n)
        contrast = contrasts.get(row['run_id'])
        level = row['factor_level'].replace('_', r'\_')
        label = 'control' if row['factor'] == 'control' else level
        if row['factor'] == 'seed':
            label = 'greedy seed ' + level
        rows.append([SHORT_MODEL[row['model_id']], label, f'{100*k/n:.3f}',
                     f'[{100*lo:.2f}, {100*hi:.2f}]',
                     f"{contrast['delta_pp']:+.3f}" if contrast else '---',
                     pformat(contrast['p_holm']) if contrast else '---'])
    rows.append(['Phi-3.5-mini', 'sampling seeds 0/1/2', r'\multicolumn{4}{c}{3 planned cells: not run}'])
    tex_table('master_results.tex',
              'All 31 archived cells and three missing Phi sampling cells. Each completed cell has 800 items. Accuracy and Wilson intervals are percentages; differences are percentage points against the same-model control. Exact McNemar p-values use Holm correction over 27 contrasts. Dashes indicate no contrast (control or the single 7B cell); no 7B control exists. Intervals are pointwise conditional approximations.',
              'tab:master', r'Model & Configuration & Acc. (\%) & Wilson 95\% & $\Delta$ (pp) & Holm $p$',
              'llrrrr', rows)


if __name__ == '__main__':
    main()

