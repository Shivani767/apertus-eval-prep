"""Regenerate the master results table from committed analysis outputs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
stats = json.loads((ROOT / 'paper/analysis/statistics.json').read_text())
audited = json.loads((ROOT / 'paper/analysis/audited_statistics.json').read_text())

import sys
sys.path.insert(0, str(ROOT / 'scripts'))
from paper_common import load_paper_data, SHORT_MODEL

data = load_paper_data()
assert not data['problems'], data['problems']
models = ['Phi-3.5-mini', 'Qwen2.5-3B', 'SmolLM2-1.7B']
acc = {}
for (model, factor, level), record in data['cells'].items():
    score = record['overall']
    value = 100 * score['correct'] / score['n']
    assert 0 <= value <= 100
    key = 'control' if factor == 'control' else f'{factor}={level}'
    acc[(SHORT_MODEL[model], key)] = value
assert len(acc) == 31
assert acc[('Qwen2.5-3B', 'prompt_id=concise')] == 51.25
holm = {(r['model'], r['factor'], r['level']): r['p_holm'] for r in audited['contrasts']}

def cell(m, factor, level):
    key = (m, f'{factor}={level}')
    value = acc[key]
    delta = value - acc[(m, 'control')]
    p = holm.get((m, factor, level))
    star = '$^{\\ast}$' if p is not None and p < 0.05 else ''
    return f'{value:.3f}', f'{delta:+.3f}{star}'

def row(factor, level):
    cols = []
    for m in models:
        if (m, f'{factor}={level}') in acc:
            a, d = cell(m, factor, level)
            cols += [a, d]
        else:
            cols += ['--', '--']
    name = {'prompt_id': 'Prompt', 'quantization': 'Quant', 'backend': 'Backend',
            'seed': 'Seed', 'sampled': 'Sample'}[factor]
    display = level.replace('t0.7_seed', 'T0.7 s')
    return f'{name} & {display} & ' + ' & '.join(cols) + r' \\'

sections = [
    ('Control configuration (baseline)', 'control', ['control']),
    ('Prompt variations', 'prompt_id', ['concise', '5shot']),
    ('Quantization (weight-only, bitsandbytes)', 'quantization', ['int8', 'int4']),
    ('Infrastructure backend', 'backend', ['vllm']),
    ('Greedy decoding seed', 'seed', ['1', '2']),
    (r'Sampling (temperature 0.7, top-$p$ 0.95)', 'sampled', ['t0.7_seed0', 't0.7_seed1', 't0.7_seed2']),
]
body = []
for title, factor, levels in sections:
    body.append(r'\multicolumn{8}{c}{\textit{' + title + r'}} \\')
    for level in levels:
        if factor == 'control':
            cols = ' & '.join(f"{acc[(m, 'control')]:.3f} & --" for m in models)
            body.append(' & Default & ' + cols + r' \\')
        else:
            body.append(row(factor, level))
    body.append(r'\midrule')
seventh = f"{acc[('Qwen2.5-7B', 'quantization=int4')]:.3f}" + r'\%; no control'
text = r'''% Generated by regenerate_master_table.py -- do not edit.
\begin{table}[tbp]
\centering\footnotesize
\caption{Master results table: all 31 completed configurations. Accuracy in
\% with paired differences from each model's control in percentage points.
Exact McNemar $p$-values with Holm correction over the full 27-contrast
family; $^{\ast}$ marks adjusted $p<0.05$. Phi-3.5-mini sampling cells were
not executed and are left blank.}
\label{tab:master}
\begin{tabular}{llcccccc}
\toprule
& & \multicolumn{2}{c}{Phi-3.5-mini} & \multicolumn{2}{c}{Qwen2.5-3B} & \multicolumn{2}{c}{SmolLM2-1.7B} \\
\cmidrule(lr){3-4} \cmidrule(lr){5-6} \cmidrule(lr){7-8}
Factor & Level & Acc. & $\Delta$ & Acc. & $\Delta$ & Acc. & $\Delta$ \\
\midrule
''' + '\n'.join(body[:-1]) + r'''
\multicolumn{8}{c}{\textit{Single-cell model}} \\
Qwen2.5-7B & INT4 & \multicolumn{6}{c}{''' + seventh + r'''} \\
\bottomrule
\end{tabular}

\smallskip
\noindent\textbf{Reading guide:} Each row is one configuration cell;
$\Delta$ is the paired percentage-point change from that model's control.
$^{\ast}$ marks Holm-adjusted $p<0.05$ (non-significance is not evidence of
no effect). Qwen2.5-7B has no comparable control and is excluded from
ranking analyses. The three absent Phi sampling cells are prospective runs,
not missing measurements that can be recovered from existing artifacts.
\end{table}
'''
(ROOT / 'paper/tables/master_results.tex').write_text(text)
print('master_results.tex regenerated from analysis JSONs')
